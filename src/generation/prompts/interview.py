from textwrap import dedent


def create_prompt(answer):
    return dedent(f"""
    아래 면접 답변을 분석하세요.

    분석 절차:
    1. 답변이 STAR 구조로 분석 가능한 경험 기반 답변인지 판단합니다.
    2. STAR 구조 분석이 가능하면 Situation, Task, Action, Result로 정리합니다.
    3. STAR 구조 분석이 불가능하더라도 답변의 핵심 내용과 특성을 분석합니다.
    4. 답변의 강점과 개선점을 작성합니다.

    반드시 아래 JSON 형식으로 출력하세요.

    {{
      "is_star_applicable": true,
      "star": {{
        "situation": "",
        "task": "",
        "action": "",
        "result": ""
      }},
      "strengths": [],
      "improvements": []
    }}

    판단 기준:

    is_star_applicable:
    - 특정 경험, 프로젝트, 업무 사례, 문제 해결 과정이 포함되어 STAR 구조 분석이 가능하면 true
    - 경험 기반 답변이라 일부 STAR 요소가 부족해도 분석 가능하면 true
    - 가치관, 의견, 지원 동기, 직무 이해, 입사 후 포부, 존경하는 인물 설명 중심이면 false

    STAR 작성 기준:

    is_star_applicable=true:
    - Situation: 경험이 발생한 배경과 상황
    - Task: 당시 맡은 역할 또는 해결해야 했던 목표
    - Action: 문제 해결을 위해 수행한 행동과 과정
    - Result: 행동 이후 발생한 결과 또는 변화

    is_star_applicable=false:
    - 해당 경우 star 객체는 STAR 구조가 아닌 답변 분석용 필드로 사용합니다.
    - Situation: 답변의 주제와 배경
    - Task: 답변자가 전달하려는 목적이나 주장
    - Action: 답변에서 제시한 근거, 설명, 사례
    - Result: 답변에서 확인 가능한 영향이나 변화

    추가 규칙:
    - false인 경우에도 star 객체는 유지하고 답변 내용을 기반으로 작성합니다.
    - 답변에 없는 기간, 수치, 도구, 성과, 경험을 절대 생성하지 않습니다.
    - 경험 답변이라도 설명 과정과 실제 수행 행동을 구분합니다.
    - "~해야 한다", "~필요하다"는 일반적인 설명은 실제 행동으로 작성하지 않습니다.
    - 결과 작성 시 성공, 달성, 획득 등의 성과는 답변자가 명확히 언급한 경우에만 작성합니다.
    - "인증을 위한 과정", "인증 절차 진행", "인증을 받기 위한 노력"과 같은 표현은 실제 인증 완료를 의미하지 않으므로 결과에서 "인증 획득"으로 단정하지 않습니다.
    - 목표, 필요 조건, 업무 설명과 실제 수행한 역할을 구분합니다.
    - 답변자가 직접 수행했다고 표현하지 않은 업무나 행동은 Action으로 작성하지 않습니다.
    - 단순한 변화, 배운 점, 경험의 영향은 답변에 근거하여 작성합니다.
    - 특정 STAR 요소에 대한 근거가 답변에 없는 경우 해당 항목은 "답변에서 확인되지 않음"으로 작성합니다.
    - strengths와 improvements 작성 시 답변에 직접 표현된 내용 또는 명확히 추론 가능한 범위만 사용합니다.
    - 답변에 없는 역량(예: 리더십, 창의성, 협업 능력 등)을 근거 없이 부여하지 않습니다.
    - STAR 요소가 부족하더라도 null을 사용하지 않습니다.
    - strengths는 답변 내용에 근거하여 최소 1개 작성합니다.
    - improvements는 답변 내용에 근거하여 최소 1개 작성합니다.
    - JSON 외의 설명이나 마크다운을 출력하지 않습니다.

    면접 답변:
    {answer}
    """)