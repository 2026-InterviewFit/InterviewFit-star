from textwrap import dedent


def create_prompt(question, answer):
    return dedent(f"""
    면접 질문과 면접 답변을 함께 분석한다.

    분석 절차:
    1. 면접 질문의 유형과 답변 내용을 확인한다.
    2. 질문과 답변에 경험 기반 상황 또는 가정된 상황이 있는지 확인하고 STAR 구조로 분석할 수 있는지 판단한다.
    3. STAR 분석이 가능하면 질문과 답변에서 확인되는 근거를 바탕으로 situation, task, action, result를 작성한다.
    4. 답변에 명시되지 않은 사실, 경험, 수치, 성과, 행동은 생성하지 않는다.

    판단 기준:

    is_star_applicable=true:
    - 프로젝트 경험이 포함된 경우
    - 문제 해결 경험이 포함된 경우
    - 갈등 해결 경험이 포함된 경우
    - 협업 경험이 포함된 경우
    - 실패 또는 성공 경험이 포함된 경우
    - 직무 역량을 보여주는 경험이 포함된 경우
    - 직무 적합성과 관련된 실제 경험이나 구체적인 대응 방법이 포함된 경우
    - 질문은 일반적이지만 답변이 실제 프로젝트, 업무 또는 경험으로 이어지는 경우
    - 가상 상황에서 협업, 문제 해결 등과 관련된 구체적인 행동 방법을 제시하는 경우

    is_star_applicable=false:
    - 친구나 주변 사람에 대한 평가 또는 칭찬을 설명하는 경우
    - 존경하는 사람이나 만나고 싶은 사람을 설명하는 경우
    - 취미, 좋아하는 것 등 개인 취향을 설명하는 경우
    - 스트레스 해소 방법 등 STAR 분석과 직접적인 관련이 없는 개인 생활을 설명하는 경우
    - 가상 상황이지만 구체적인 행동이나 대응 방법 없이 가치관이나 태도만 설명하는 경우
    - 질문과 답변에서 경험, 상황, 구체적인 행동을 확인하기 어려운 경우

    가정 상황 처리:
    - 질문이 "~한다면", "~일 경우", "~상황이라면", "~어떻게 하겠습니까?"와 같이 가정된 상황을 제시하면 질문의 상황을 Situation으로 사용한다.
    - 가정 상황은 실제 경험으로 간주하지 않는다.
    - 가정 상황에 대한 답변자의 대응 방법은 제시한 행동이나 대응 방식으로 작성하며 실제 수행한 경험처럼 표현하지 않는다.

    STAR 작성 기준:
    situation:
    - 실제 경험이라면 답변에서 확인되는 경험의 배경과 상황을 요약 및 정리해서 작성한다.
    - 가정형 질문이라면 질문에서 제시한 가정 상황을 요약 및 정리해서 작성한다.
    task:
    - 맡은 역할, 해결해야 했던 문제, 달성해야 했던 목표를 요약 및 정리해서 작성한다.
    - 가정형 질문이라면 해당 상황에서 수행해야 하는 목표나 역할을 요약 및 정리해서 작성한다.
    - 목표와 실제 행동을 구분하여 작성한다.
    action:
    - 답변자가 수행한 행동과 과정을 요약 및 정리해서 작성한다.
    - 가정형 질문이라면 답변자가 제시한 대응 방법과 행동을 요약 및 정리해서 작성한다.
    - 일반적인 설명이나 추상적인 행동이 아닌, 답변에서 확인되는 행동을 중심으로 요약 및 정리해서 작성한다.
    result:
    - 행동 이후 답변에서 확인되는 결과, 변화 또는 영향을 요약 및 정리해서 작성한다.
    - 성공, 달성, 획득 등의 성과는 답변에서 명확하게 확인되는 경우에만 작성한다.
    strengths:
    - 답변에서 확인되는 강점을 작성한다.
    improvements:
    - 답변에서 개선이 필요한 부분을 작성한다.

    is_star_applicable=false인 경우:
    - star 객체를 유지한다.
    - situation, task, action, result는 질문과 답변에서 확인되는 근거를 바탕으로 요약 및 정리해서 작성한다.
    - 각 요소의 근거를 확인할 수 없는 경우 "답변에서 확인되지 않음"으로 작성한다.
    - strengths와 improvements는 답변을 바탕으로 작성한다.

    STAR 요소 확인 불가 규칙:
    - situation, task, action, result 중 질문 또는 답변에서 근거를 확인할 수 없는 요소는 반드시 "답변에서 확인되지 않음"으로 작성한다.
    - 이 규칙은 실제 경험형, 가정형, 일반적인 질문 등 모든 질문에 적용한다.
    - 질문에서 제공된 가정 상황은 situation의 근거로 사용할 수 있다.
    - 특정 요소의 근거가 일부만 확인되면 확인 가능한 내용만 작성한다.
    - 확인되지 않는 요소를 빈 문자열(""), null, "없음" 등으로 작성하지 않는다.
    - 확인되지 않는 요소를 임의의 내용으로 채우거나 답변에 없는 내용을 추론하여 생성하지 않는다.
    - STAR 객체는 항상 situation, task, action, result 네 가지 필드를 포함한다.

    공통 작성 규칙:
    - 인증을 위한 과정이나 노력만 언급된 경우 인증 획득으로 판단하지 않는다.
    - strengths는 최소 1개, improvements는 최소 1개 작성한다.
    - 모든 출력 내용은 간결한 명사형 또는 "~함" 체로 작성한다.
    - JSON 외의 설명이나 마크다운은 출력하지 않는다.

    출력 형식:
    {{
      "is_star_applicable": true,
      "star": {{
        "situation": "",
        "task": "",
        "action": "",
        "result": ""
      }},
      "strengths": [],
      "improvements": []
    }}

    면접 질문:
    {question}

    면접 답변:
    {answer}
    """)